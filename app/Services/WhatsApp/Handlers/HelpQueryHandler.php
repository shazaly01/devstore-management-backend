<?php

namespace App\Services\WhatsApp\Handlers;

use App\Services\WhatsApp\Contracts\QueryHandlerInterface;

class HelpQueryHandler implements QueryHandlerInterface
{
    public function getIntentName(): string
    {
        return 'help_menu';
    }

    public function getDescription(): string
    {
        return 'عرض دليل الاستعلامات اليومية السريعة بألفاظ مباشرة وسهلة لتوجيه المدير.';
    }

    public function handle(array $parsedIntent): string
    {
        $output = "📋 *دليل الاستعلامات السريعة للنظام*\n";
        $output .= "-----------------------------------\n";
        $output .= "مرحباً بك! يمكنك الاستعلام مباشرة بكتابة أي جملة من الجمل التالية:\n\n";

        $output .= "💵 *1. الكاش والسيولة (الخزائن والبنوك):*\n";
        $output .= "• `الكاش` أو `السيولة`\n";
        $output .= "• `رصيد الخزينة` أو `رصيد البنك`\n\n";

        $output .= "📊 *2. المبيعات:*\n";
        $output .= "• `مبيعات اليوم` أو `دخل اليوم`\n";
        $output .= "• `مبيعات أمس`\n";
        $output .= "• `مبيعات هذا الأسبوع` أو `مبيعات الأسبوع الماضي`\n";
        $output .= "• `مبيعات هذا الشهر` أو `مبيعات الشهر الماضي`\n\n";

        $output .= "💸 *3. المصروفات:*\n";
        $output .= "• `مصروفات اليوم` أو `صرفيات اليوم`\n";
        $output .= "• `مصروفات أمس`\n";
        $output .= "• `مصروفات هذا الشهر` أو `مصروفات الشهر الماضي`\n\n";

        $output .= "📦 *4. المخزون والأسعار والنواقص:*\n";
        $output .= "• `رصيد وسعر [اسم الصنف]` (مثال: `رصيد وسعر استيكر`)\n";
        $output .= "• `النواقص` (الأصناف المنتهية أو القريبة من النفاد)\n\n";

        $output .= "👥 *5. الحسابات والديون:*\n";
        $output .= "• `ديون العملاء` أو `أرصدة العملاء`\n";
        $output .= "• `مستحقات الموردين` أو `ديون الموردين`\n";
        $output .= "• `رصيد [اسم الشخص أو الشركة]` (مثال: `رصيد محمد أحمد`)\n";
        $output .= "• `آخر فاتورة لعميل [الاسم]` (مثال: `آخر فاتورة لعميل طارق`)\n\n";

        $output .= "-----------------------------------\n";
        $output .= "💡 *ملاحظة*: يمكنك كتابة استفسارك بصيغتك المعتادة في أي وقت وسأجيبك فوراً.";

        return trim($output);
    }
}