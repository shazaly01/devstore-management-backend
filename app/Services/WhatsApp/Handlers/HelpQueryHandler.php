<?php

namespace App\Services\WhatsApp\Handlers;

use App\Services\WhatsApp\Contracts\QueryHandlerInterface;

class HelpQueryHandler implements QueryHandlerInterface
{
    public function getIntentName(): string
    {
        return 'help_menu';
    }

    public function getDescription(): string
    {
        return 'عرض دليل الأوامر والاستعلامات المتاحة وكيفية كتابتها للنظام لتوجيه المستخدم.';
    }

    public function handle(array $parsedIntent): string
    {
        $output = "📋 *دليل الاستعلامات السريعة لنظام ERP*\n";
        $output .= "-----------------------------------\n";
        $output .= "مرحباً بك! يمكنك الاستعلام عن بياناتك مباشرة بنسخ أو كتابة إحدى الصيغ التالية:\n\n";

        $output .= "💵 *1. الموقف المالي والسيولة النقدية:*\n";
        $output .= "• `موقف السيولة` أو `الكاش`\n";
        $output .= "• `رصيد الخزائن` أو `أرصدة البنوك`\n\n";

        $output .= "📊 *2. المبيعات والإيرادات:*\n";
        $output .= "• `مبيعات اليوم` أو `مبيعات أمس`\n";
        $output .= "• `مبيعات هذا الأسبوع` أو `مبيعات الأسبوع الماضي`\n";
        $output .= "• `مبيعات هذا الشهر` أو `مبيعات الشهر الماضي`\n";
        $output .= "• `مبيعات فرع مدني` أو `مبيعات فرع أمدرمان`\n\n";

        $output .= "💸 *3. المصروفات والنفقات:*\n";
        $output .= "• `مصروفات اليوم` أو `مصروفات أمس`\n";
        $output .= "• `مصروفات هذا الأسبوع` أو `مصروفات هذا الشهر`\n\n";

        $output .= "📦 *4. المخزون والأسعار والنواقص:*\n";
        $output .= "• `رصيد وسعر [اسم الصنف]` (مثال: `رصيد وسعر بنر 130`)\n";
        $output .= "• `تقرير النواقص` أو `نواقص فرع أمدرمان`\n\n";

        $output .= "👥 *5. كشف الحسابات والديون:*\n";
        $output .= "• `رصيد [اسم العميل أو المورد]` (مثال: `رصيد شركة الأمل`)\n";
        $output .= "• `كبار المدينين` (أعلى ديون مستحقة للشركة)\n";
        $output .= "• `كبار الموردين` (التزامات التوريد المستحقة علينا)\n";
        $output .= "• `آخر فاتورة لعميل [الاسم]` (مثال: `آخر فاتورة لعميل طارق`)\n\n";

        $output .= "-----------------------------------\n";
        $output .= "💡 *ملاحظة*: يمكنك كتابة استفسارك مباشرة بأي صياغة تريد وسيقوم النظام بالإجابة فوراً.";

        return trim($output);
    }
}